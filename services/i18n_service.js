  setLanguage: function(lang) {
    const valid = ['en', 'ta', 'hi', 'te', 'kn'];
    this.currentLang = valid.includes(lang) ? lang : 'en';
    localStorage.setItem('earthworm_lang', this.currentLang);
  },

  getLanguage: function() {
    return this.currentLang || localStorage.getItem('earthworm_lang') || 'en';
  },

  getSpeechLangCode: function() {
    const match = this.languages.find(l => l.code === this.currentLang);
    return match ? match.speechLang : 'en-IN';
  },

  getLanguageName: function() {
    const match = this.languages.find(l => l.code === this.currentLang);
    return match ? match.name : 'English';
  },

  t: function(key) {
    const lang = this.getLanguage();
    if (this.translations[lang] && this.translations[lang][key]) {
      return this.translations[lang][key];
    }
    if (this.translations['en'] && this.translations['en'][key]) {
      return this.translations['en'][key];
    }
    return key;
  }
